const I18nContext = createContext(null);

export const I18nProvider = ({ children }) => {
    const { language } = useAuth();
    const lang = language === 'am' ? 'am' : 'en';

    const t = useCallback((key, ...args) => {
        const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
        // Fall back to English before the raw key: an untranslated string is a
        // cosmetic gap, but a bare camelCase key on screen reads as a bug.
        const value = dict[key] !== undefined ? dict[key] : TRANSLATIONS.en[key];
        if (typeof value === 'function') {
            return value(...args);
        }
        return value !== undefined ? value : key;
    }, [lang]);

    const value = useMemo(() => ({
        lang,
        t,
        translations: TRANSLATIONS[lang] || TRANSLATIONS.en,
    }), [lang, t]);

    return (
        <I18nContext.Provider value={value}>
            {children}
        </I18nContext.Provider>
    );
};

export const useI18n = () => {
    const context = useContext(I18nContext);
    if (!context) {
        throw new Error('useI18n must be used within an I18nProvider');
    }
    return context;
};

export default I18nContext;